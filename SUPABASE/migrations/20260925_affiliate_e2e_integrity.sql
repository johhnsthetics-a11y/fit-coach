-- Existing production has historical phone duplicates. Do not mutate them.
-- Only reject a NEW/CHANGED phone that would create another duplicate.
create or replace function public.coachfit_reject_new_duplicate_student_phone()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_phone text;
  v_old_phone text;
begin
  v_phone := regexp_replace(coalesce(new.phone, ''), '\\D', '', 'g');

  if tg_op = 'UPDATE' then
    v_old_phone := regexp_replace(coalesce(old.phone, ''), '\\D', '', 'g');
    if new.coach_id is not distinct from old.coach_id
       and v_phone is not distinct from v_old_phone then
      return new;
    end if;
  end if;

  if new.coach_id is not null and v_phone <> '' and exists (
    select 1
    from public.students as students
    where students.coach_id = new.coach_id
      and students.id is distinct from new.id
      and regexp_replace(coalesce(students.phone, ''), '\\D', '', 'g') = v_phone
  ) then
    raise exception 'Ja existe aluno/paciente deste profissional com este telefone.'
      using errcode = '23505';
  end if;

  return new;
end;
$$;

revoke all on function public.coachfit_reject_new_duplicate_student_phone() from public, anon, authenticated;

drop trigger if exists coachfit_reject_new_duplicate_student_phone on public.students;
create trigger coachfit_reject_new_duplicate_student_phone
before insert or update of coach_id, phone on public.students
for each row execute function public.coachfit_reject_new_duplicate_student_phone();

-- The app subscription paid to Coach Fit Pro is independent from the professional's
-- own invoice field (students.payment). For affiliate professionals, only the
-- persisted app subscription state gates app tools.
create or replace function public.coachfit_student_financial_access_by_invite(p_invite_code text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.student_invites as invites
    join public.students as students
      on students.id = invites.student_id
     and students.coach_id = invites.coach_id
    where invites.code = trim(p_invite_code)
      and invites.status = 'active'
      and (invites.expires_at is null or invites.expires_at > now())
      and (
        not public.coachfit_professional_requires_app_payment(invites.coach_id)
        or (
          (
            students.app_payment_status = 'active'
            and (
              students.app_subscription_expires_at is null
              or students.app_subscription_expires_at > now()
            )
          )
          or students.access_override_until > now()
        )
      )
  );
$$;

