-- Atomic webhook processor for affiliate student/patient purchases.
-- Only the service role used by the Edge Function can invoke it.
create or replace function public.process_cartpanda_student_payment_event(
  p_event_id text,
  p_event_type text,
  p_correlation_id text,
  p_buyer_email text,
  p_provider_order_id text,
  p_provider_subscription_id text,
  p_product_id text,
  p_product_name text,
  p_amount_cents integer,
  p_status text,
  p_confirmed_payment boolean,
  p_provider_event_at timestamptz,
  p_period_ends_at timestamptz,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_event public.payment_webhook_events%rowtype;
  v_session public.student_checkout_sessions%rowtype;
  v_student public.students%rowtype;
  v_effective_status text;
  v_event_at timestamptz := coalesce(p_provider_event_at, now());
  v_rank integer;
  v_affiliate_email text;
  v_existing_payment public.affiliate_student_payments%rowtype;
  v_period_end timestamptz;
  v_now timestamptz := now();
begin
  if nullif(btrim(p_event_id), '') is null then
    raise exception 'event_id obrigatorio' using errcode = '22023';
  end if;

  if p_status not in ('pending', 'active', 'past_due', 'canceled', 'refunded', 'chargeback') then
    raise exception 'status de pagamento invalido' using errcode = '22023';
  end if;

  -- Serialize exact replays before doing any state transition.
  perform pg_advisory_xact_lock(hashtextextended(p_event_id, 0));

  insert into public.payment_webhook_events (
    provider,
    event_id,
    event_type,
    buyer_email,
    provider_order_id,
    provider_subscription_id,
    product_id,
    product_name,
    amount_cents,
    subscription_status,
    processed,
    processing_error,
    payload,
    provider_event_at
  )
  values (
    'cartpanda',
    p_event_id,
    nullif(p_event_type, ''),
    nullif(lower(btrim(p_buyer_email)), ''),
    nullif(p_provider_order_id, ''),
    nullif(p_provider_subscription_id, ''),
    nullif(p_product_id, ''),
    nullif(p_product_name, ''),
    p_amount_cents,
    p_status,
    false,
    null,
    coalesce(p_payload, '{}'::jsonb),
    v_event_at
  )
  on conflict (event_id) do nothing;

  select * into v_event
  from public.payment_webhook_events
  where event_id = p_event_id
  for update;

  if v_event.processed then
    return jsonb_build_object(
      'ok', true,
      'processed', true,
      'reason', 'duplicate_event'
    );
  end if;

  if nullif(p_correlation_id, '') is not null
     and p_correlation_id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' then
    select * into v_session
    from public.student_checkout_sessions
    where checkout_token = p_correlation_id::uuid
    limit 1
    for update;
  elsif nullif(p_provider_subscription_id, '') is not null then
    select * into v_session
    from public.student_checkout_sessions
    where provider_subscription_id = p_provider_subscription_id
    order by created_at desc
    limit 1
    for update;
  end if;

  if v_session.id is null then
    update public.payment_webhook_events
    set processing_error = 'student_checkout_not_found'
    where event_id = p_event_id;

    return jsonb_build_object(
      'ok', true,
      'processed', false,
      'reason', 'student_checkout_not_found'
    );
  end if;

  -- The purchased product is contractually R$25.00/month.
  -- Reject a confirmed activation if CartPanda reports a different or missing amount.
  if p_status = 'active' and p_confirmed_payment
     and coalesce(p_amount_cents, -1) <> 2500 then
    update public.payment_webhook_events
    set processed = true,
        processing_error = 'unexpected_student_amount'
    where event_id = p_event_id;

    return jsonb_build_object(
      'ok', false,
      'processed', true,
      'reason', 'unexpected_student_amount',
      'status', 'pending'
    );
  end if;

  v_effective_status := case
    when p_status = 'active' and not p_confirmed_payment then 'pending'
    else p_status
  end;

  v_rank := case v_effective_status
    when 'chargeback' then 60
    when 'refunded' then 50
    when 'canceled' then 40
    when 'past_due' then 30
    when 'active' then 20
    else 10
  end;

  -- Ignore stale/out-of-order provider events. Same-timestamp terminal states win.
  if v_session.last_provider_event_at is not null
     and (
       v_event_at < v_session.last_provider_event_at
       or (
         v_event_at = v_session.last_provider_event_at
         and v_rank < v_session.last_provider_event_rank
       )
     ) then
    update public.payment_webhook_events
    set processed = true,
        processing_error = 'stale_event_ignored'
    where event_id = p_event_id;

    return jsonb_build_object(
      'ok', true,
      'processed', true,
      'reason', 'stale_event_ignored',
      'studentId', v_session.student_id,
      'coachId', v_session.coach_id
    );
  end if;

  select * into v_student
  from public.students
  where id = v_session.student_id
    and coach_id = v_session.coach_id
  for update;

  if v_student.id is null then
    update public.payment_webhook_events
    set processing_error = 'student_not_found'
    where event_id = p_event_id;

    return jsonb_build_object(
      'ok', true,
      'processed', false,
      'reason', 'student_not_found'
    );
  end if;

  if nullif(v_session.affiliate_email_snapshot, '') is null then
    select lower(btrim(users.email)) into v_affiliate_email
    from public.users as users
    join public.affiliate_professionals as affiliates
      on affiliates.email = lower(btrim(users.email))
     and affiliates.active = true
    where users.id = v_session.coach_id;

    if v_affiliate_email is not null then
      update public.student_checkout_sessions
      set affiliate_email_snapshot = v_affiliate_email
      where id = v_session.id;
      v_session.affiliate_email_snapshot := v_affiliate_email;
    end if;
  end if;

  update public.student_checkout_sessions
  set
    status = v_effective_status,
    buyer_email = nullif(lower(btrim(p_buyer_email)), ''),
    provider_order_id = coalesce(nullif(p_provider_order_id, ''), provider_order_id),
    provider_subscription_id = coalesce(nullif(p_provider_subscription_id, ''), provider_subscription_id),
    amount_cents = coalesce(p_amount_cents, amount_cents),
    paid_at = case when v_effective_status = 'active' then v_event_at else paid_at end,
    last_provider_event_at = v_event_at,
    last_provider_event_id = p_event_id,
    last_provider_event_rank = v_rank,
    updated_at = v_now
  where id = v_session.id;

  if v_effective_status = 'active' then
    v_period_end := case
      when p_period_ends_at is not null and p_period_ends_at > v_event_at then p_period_ends_at
      else (v_event_at + interval '1 month')
    end;

    update public.students
    set
      app_payment_status = 'active',
      app_subscription_started_at = coalesce(app_subscription_started_at, v_event_at),
      app_subscription_expires_at = greatest(
        coalesce(app_subscription_expires_at, '-infinity'::timestamptz),
        v_period_end
      ),
      updated_at = v_now
    where id = v_session.student_id
      and coach_id = v_session.coach_id;

    v_affiliate_email := nullif(lower(btrim(v_session.affiliate_email_snapshot)), '');

    if v_affiliate_email is not null then
      insert into public.affiliate_student_payments (
        webhook_event_id,
        coach_id,
        student_id,
        affiliate_email,
        status,
        paid_at,
        payment_month,
        revenue_cents,
        provider_amount_cents,
        commission_rate,
        commission_cents,
        provider,
        provider_order_id,
        provider_subscription_id,
        updated_at
      )
      values (
        p_event_id,
        v_session.coach_id,
        v_session.student_id,
        v_affiliate_email,
        'paid',
        v_event_at,
        date_trunc('month', v_event_at)::date,
        2500,
        p_amount_cents,
        0.2500,
        625,
        'cartpanda',
        nullif(p_provider_order_id, ''),
        nullif(p_provider_subscription_id, ''),
        v_now
      )
      on conflict (webhook_event_id) do nothing;
    end if;

  elsif v_effective_status in ('refunded', 'chargeback') then
    update public.students
    set
      app_payment_status = v_effective_status,
      updated_at = v_now
    where id = v_session.student_id
      and coach_id = v_session.coach_id;

    select * into v_existing_payment
    from public.affiliate_student_payments as payments
    where payments.coach_id = v_session.coach_id
      and payments.student_id = v_session.student_id
      and payments.status = 'paid'
      and (
        (
          nullif(p_provider_order_id, '') is not null
          and payments.provider_order_id = p_provider_order_id
        )
        or (
          nullif(p_provider_order_id, '') is null
          and nullif(p_provider_subscription_id, '') is not null
          and payments.provider_subscription_id = p_provider_subscription_id
        )
      )
    order by payments.paid_at desc
    limit 1
    for update;

    if v_existing_payment.id is not null then
      update public.affiliate_student_payments
      set
        status = v_effective_status,
        reversal_event_id = p_event_id,
        reversed_at = v_event_at,
        updated_at = v_now
      where id = v_existing_payment.id;
    end if;

  elsif v_effective_status in ('past_due', 'canceled') then
    update public.students
    set
      app_payment_status = v_effective_status,
      updated_at = v_now
    where id = v_session.student_id
      and coach_id = v_session.coach_id;

  elsif v_effective_status = 'pending' then
    -- A pending renewal must not revoke a still-current paid period.
    if v_student.app_payment_status <> 'active'
       or v_student.app_subscription_expires_at is null
       or v_student.app_subscription_expires_at <= v_now then
      update public.students
      set app_payment_status = 'pending', updated_at = v_now
      where id = v_session.student_id
        and coach_id = v_session.coach_id;
    end if;
  end if;

  update public.payment_webhook_events
  set
    processed = true,
    processing_error = null,
    subscription_status = v_effective_status,
    provider_event_at = v_event_at
  where event_id = p_event_id;

  return jsonb_build_object(
    'ok', true,
    'processed', true,
    'reason', 'processed',
    'studentId', v_session.student_id,
    'coachId', v_session.coach_id,
    'status', v_effective_status
  );
end;
$$;

